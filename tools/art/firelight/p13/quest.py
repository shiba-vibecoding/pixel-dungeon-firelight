def reward(light, deep, mark, f):
    """32 x 48: a low podium of stone, a beam of the giver's light rising from it (the item is drawn by the game on top),
    four marks circling slowly."""
    L, D = hx(light), hx(deep)
    c = Cv(32, 48)
    beam_w = 7 + (f % 4 in (1, 2))
    for y in range(4, 40):
        t = (40 - y) / 36
        for x in range(16 - beam_w, 16 + beam_w + 1):
            d = abs(x - 16) / beam_w
            a = int(255 * (1 - t) * (1 - d) * 0.75)
            if a > 20: c.put(x, y, mix(D, L, 1 - d) if d < 0.6 else D, a)
    for y in range(38, 46):
        for x in range(6, 26):
            if y == 38: col = mix(hx('#9fa896'), L, 0.4)
            elif y < 42: col = hx('#7a8173') if x > 7 else hx('#555950')
            else: col = hx('#3b3e36')
            if y == 45: col = hx('#0b0b09')
            c.put(x, y, col)
    c.ring(16, 38, 9, L, 200, sq=0.35)
    for k in range(4):
        a = f / 8 * 6.2832 + k * 1.5708
        x, y = 16 + math.cos(a) * 11, 28 + math.sin(a) * 4
        front = math.sin(a) > 0
        col = L if front else D
        if mark == 'spark' or mark == 'star': c.plus(x, y, col, 1)
        elif mark == 'ring': c.ring(x, y, 1.6, col)
        elif mark == 'blade': c.line(x - 1, y + 1, x + 1, y - 1, col)
        elif mark == 'shield': c.disc(x, y, 1.2, col)
        else: c.put(x, y, col); c.put(x + 1, y, col)
    return c.im


def rewards():
    return rows([strip([reward(l, d, m, f) for f in range(8)]) for _, l, d, m in REWARDS])


