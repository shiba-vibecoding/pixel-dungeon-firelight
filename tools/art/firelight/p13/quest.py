def frame_dialog():
    """48 x 48, slice 16: an iron band with a coal edge below, rivets as embers; the inside warm dark stone."""
    c = Cv(48, 48); iron, iron_hi, coal, deep = hx('#3b3e36'), hx('#7a8173'), hx('#6e161a'), hx('#1f1a14')
    for y in range(48):
        for x in range(48):
            if (x in (0, 47) and y in (0, 47)): continue
            d = min(x, y, 47 - x, 47 - y)
            col = hx('#0b0b09') if d == 0 else (iron_hi if d == 1 and y < 24 else (iron if d <= 3 else (hx('#0b0b09') if d == 4 else deep)))
            if d in (1, 2, 3) and y > 44: col = hx('#e8641f') if d == 1 else coal              # the fire's edge at the bottom
            if d == 1 and 24 <= y <= 44 and x in (1, 46): col = mix(iron_hi, hx('#e8641f'), (y - 24) / 20)
            c.put(x, y, col)
    for (x, y) in ((6, 6), (41, 6), (6, 41), (41, 41)):
        c.put(x, y, hx('#ffcc66')); c.put(x + 1, y, hx('#e8641f')); c.put(x, y + 1, hx('#e8641f')); c.put(x + 1, y + 1, hx('#6e161a'))
    for y in range(40, 43):                      # the glow inside the bottom edge (kept within the 8 px slice: the middle stays flat)
        for x in range(5, 43):
            c.put(x, y, mix(deep, hx('#ff9a3a'), 0.16 if y == 42 else 0.08))
    return c.im


def frame_portrait():
    """64 x 64: a niche of dark stone for the 48 x 48 portrait at (8, 8); the fire glows up from its sill."""
    c = Cv(64, 64)
    for y in range(64):
        for x in range(64):
            if (x in (0, 63) and y in (0, 63)): continue
            d = min(x, y, 63 - x, 63 - y)
            if d == 0: col = hx('#0b0b09')
            elif d <= 2: col = hx('#a8804e') if y < 32 else (hx('#e0b878') if y > 60 else hx('#74583c'))
            elif d <= 5: col = hx('#4a3424') if y < 58 else hx('#e8641f')
            elif d == 6: col = hx('#0b0b09')
            else:
                k = 63 - 7 - y
                col = mix(hx('#17130e'), hx('#ff9a3a'), 0.20 if k < 6 else (0.10 if k < 14 else (0.04 if k < 26 else 0)))
            c.put(x, y, col)
    return c.im


def progress():
    """the quest bar: a track 48 x 16 (slice 6), then the fill's steps 16 x 16 (empty, ember, gold, done) and a tick."""
    track = Cv(48, 16)
    for y in range(3, 13):
        for x in range(48):
            d = min(x, y - 3, 47 - x, 12 - y)
            track.put(x, y, hx('#0b0b09') if d == 0 else (hx('#55524c') if d == 1 and y < 8 else (hx('#2a241c'))))
    tiles = []
    for kind in ('empty', 'ember', 'gold', 'done'):
        t = Cv(16, 16)
        for y in range(5, 11):
            for x in range(16):
                if kind == 'empty': col = hx('#2a241c')
                elif kind == 'ember': col = hx('#ff9a3a') if y < 7 else (hx('#e8641f') if y < 9 else hx('#b22a2a'))
                elif kind == 'gold': col = hx('#ffeba4') if y < 7 else (hx('#ffcc66') if y < 9 else hx('#e8641f'))
                else: col = hx('#b6f07a') if y < 7 else (hx('#7ad05a') if y < 9 else hx('#3a7a2a'))
                t.put(x, y, col)
        tiles.append(t.im)
    tick = grid(["................", "..........kk....", ".........kGk....", "........kGk.....", "..kk...kGk......",
                 "..kGk.kGk.......", "...kGkGk........", "....kGk.........", ".....k..........", "................",
                 "................", "................", "................", "................", "................", "................"], {k: hx(v) for k, v in PAL.items()})
    return strip([track.im] + tiles + [tick])


def icons():
    pal = {k: hx(v) for k, v in PAL.items()}
    from bust import Bust
    def outline(im):
        out = im.copy(); p, q = im.load(), out.load()
        for y in range(im.height):
            for x in range(im.width):
                if p[x, y][3]: continue
                if any(0 <= x + dx < im.width and 0 <= y + dy < im.height and p[x + dx, y + dy][3] and p[x + dx, y + dy][:3] != pal['k']
                       for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))): q[x, y] = pal['k'] + (255,)
        return out
    g = lambda t: outline(grid([(r + '.' * 16)[:16] for r in (t.strip('\n').split('\n') + ['.' * 16] * 16)[:16]], pal))
    return rows([strip([g(ICONS[k]) for k in ICONS]), strip([g(BADGES[k]) for k in BADGES])])


# ---------- the smith: ore struck with a pickaxe, the dark gold nugget, the forge, the anvil ----------
def ore_hit():
    """32 x 32 x 6: a blow on a vein of dark gold — a flash, chips of rock flying, sparks, dust settling."""
    R = random.Random(13); fr = []
    chips = [(R.uniform(-1, 1), R.uniform(-1.2, -0.2), R.choice(['#5a5448', '#7a7262', '#8a7a2a', '#c8a83a'])) for _ in range(9)]
    sparks = [(R.uniform(0, 6.28), R.uniform(0.8, 1.4)) for _ in range(7)]
    for f in range(6):
        c = Cv(32, 32)
        if f < 2: c.glow(16, 16, 5 - f * 2, [hx('#fffad6'), hx('#ffcc66'), hx('#e8641f')])
        for vx, vy, col in chips:
            t = f + 1
            x, y = 16 + vx * t * 2.4, 16 + vy * t * 2.6 + 0.35 * t * t
            if f < 5: c.put(x, y, hx(col)); c.put(x + 1, y, hx(col))
        for a, sp in sparks:
            if f < 4:
                r = 3 + f * 3.2 * sp
                c.line(16 + math.cos(a) * (r - 2), 16 + math.sin(a) * (r - 2), 16 + math.cos(a) * r, 16 + math.sin(a) * r, hx('#ffeba4' if f < 2 else '#ff9a3a'))
        if f >= 3:
            for k, (x, y) in enumerate(((9, 25), (15, 27), (21, 24), (24, 27))):
                r = 1 + (f - 3) * 0.5 + (k % 2) * 0.5
                c.disc(x + (f - 3) * (k - 1.5), y - (f - 3), r, hx('#7a7262'), 170 - (f - 3) * 50)
        fr.append(c.im)
    return strip(fr)


def nugget():
    """16 x 16 x 6: a lump of dark gold (an ore of the quest); a gleam crosses it, then twinkles."""
    base = ICONS['ore']
    pal = {k: hx(v) for k, v in PAL.items()}
    fr = []
    for f in range(6):
        im = grid([r for r in base.strip('\n').split('\n')], pal); p = im.load()
        o = -4 + f * 4
        for y in range(16):
            for x in range(16):
                if p[x, y][3] and p[x, y][:3] != pal['n'] and x + y in (o + 14, o + 15): p[x, y] = pal['s'] + (255,)
        c = Cv(16, 16); c.blit(im, 0, 0)
        if f == 5: c.plus(11, 4, hx('#fffad6'), 1, tip=hx('#ffcc66'))
        fr.append(c.im)
    return strip(fr)


def forge():
    """16 x 32 x 6, a loop: the forge's mouth — coals, flame tongues licking up, sparks rising out of it."""
    R = random.Random(5); fr = []
    for f in range(6):
        c = Cv(16, 32)
        for x in range(2, 14):
            for y in range(26, 31): c.put(x, y, hx(['#6e161a', '#b22a2a', '#e8641f'][(x + y + f) % 3]))
        for k in range(4):
            x = 3 + k * 3 + (f + k) % 2; hgt = 6 + ((f * 3 + k * 5) % 7)
            for y in range(26 - hgt, 26):
                t = (26 - y) / hgt
                c.put(x, y, hx('#ffeba4' if t < 0.3 else ('#ff9a3a' if t < 0.65 else '#e8641f')))
                if t < 0.5: c.put(x + 1, y, hx('#ff9a3a'))
        for k in range(3):
            y = (24 - (f * 4 + k * 7) % 22); x = 4 + (k * 5 + f) % 9
            c.put(x, y, hx('#fffad6'))
        fr.append(c.im)
    return strip(fr)


def anvil():
    """32 x 32 x 5: the hammer meets the anvil — a white flash, a fan of sparks thrown up and out, two last embers falling."""
    R = random.Random(9); fr = []
    sp = [(R.uniform(-2.8, -0.35), R.uniform(0.9, 1.5)) for _ in range(12)]
    for f in range(5):
        c = Cv(32, 32)
        if f == 0: c.glow(16, 20, 4, [hx('#ffffff'), hx('#fffad6'), hx('#ffcc66')])
        for a, s in sp:
            r = 2 + f * 3.6 * s; x, y = 16 + math.cos(a) * r, 20 + math.sin(a) * r + 0.6 * f * f
            if f < 4: c.line(x - math.cos(a) * 2, y - math.sin(a) * 2, x, y, hx('#fffad6' if f < 2 else '#ff9a3a'))
            elif s > 1.2: c.put(x, y + 2, hx('#e8641f'))
        fr.append(c.im)
    return strip(fr)


