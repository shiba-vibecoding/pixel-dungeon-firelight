def grid(text, size):
    rows = [r for r in text.strip('\n').split('\n')]
    rows = (rows + ['.' * size] * size)[:size]
    return [(r + '.' * size)[:size] for r in rows]


def draw(text, size):
    g = grid(text, size)
    im = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    px = im.load()
    for y, row in enumerate(g):
        for x, ch in enumerate(row):
            if ch != '.':
                px[x, y] = hx(PAL[ch]) + (255,)
    # the outline: void where a transparent pixel touches a drawn one (4-neighbourhood); masks get none (tinted whole at run time)
    out = im.copy()
    po = out.load()
    for y in range(size):
        for x in range(size):
            if px[x, y][3]:
                continue
            if any(0 <= x + dx < size and 0 <= y + dy < size and px[x + dx, y + dy][3] and g[y + dy][x + dx] != 'w'
                   for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                po[x, y] = hx(PAL['k']) + (255,)
    return out


SETS = [(8, I8), (12, I12), (16, I16)]
MASKS = ('enchant', 'glyph')


def sheet():
    """The sheet: a row a size, 16 px apart; returns the image and {size: {name: [x, y, w, h]}}."""
    width = max(len(s) * n for n, s in SETS)
    im = Image.new('RGBA', (max(256, width), 48), (0, 0, 0, 0))
    where = {}
    for row, (n, icons) in enumerate(SETS):
        y = row * 16
        where[str(n)] = {}
        for i, (name, text) in enumerate(icons.items()):
            im.paste(draw(text, n), (i * n, y))
            where[str(n)][name] = [i * n, y, n, n]
    return im, where


if __name__ == '__main__':
    import os
    from c11 import DIR
    os.makedirs(DIR, exist_ok=True)
    im, _ = sheet()
    im.save(DIR + 'growth-icons.png', optimize=False)
    print('growth-icons.png', im.size)
